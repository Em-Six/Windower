local m = require('lib/model')
local storage = require('lib/storage')
local actions = require('lib/actions')
local s = m.new()
assert(#s.bars == 10 and s.bars[1].scope == 'global' and s.bars[2].scope == 'job')
assert(m.set_slot(s,1,1,'WAR',{command='/ma "Cure" <me>',label='Cure',icon=''}))
assert(m.get_slot(s,1,1,'RDM').command == '/ma "Cure" <me>')
assert(m.set_slot(s,2,1,'WAR',{command='/ja "Provoke" <t>',label='',icon=''}))
assert(m.get_slot(s,2,1,'RDM') == nil)
assert(m.create_palette(s,'raid',true))
assert(m.get_slot(s,1,1,'WHM').command == '/ma "Cure" <me>')
assert(m.get_slot(s,2,1,'WAR').command == '/ja "Provoke" <t>')
assert(m.set_slot(s,2,1,'WAR',{command='/ws "Savage Blade" <t>',label='SB',icon=''}))
assert(m.select_palette(s,'default'))
assert(m.get_slot(s,2,1,'WAR').command == '/ja "Provoke" <t>')
assert(m.select_palette(s,'raid'))
assert(m.swap_slots(s,1,1,2,1,'WAR'))
assert(m.get_slot(s,1,1,'WHM').command == '/ws "Savage Blade" <t>')
assert(m.get_slot(s,2,1,'WAR').command == '/ma "Cure" <me>')
assert(m.delete_palette(s,'raid'))
assert(not m.delete_palette(s,'default'))
assert(s.active_palette == 'default')
local normalized = m.normalize(s)
assert(normalized.bars[1].scope == 'global')
assert(m.get_slot(normalized,1,1,'WHM').command == '/ma "Cure" <me>')
assert(actions.kind('/ma "Cure" <me>') == 'magic')
assert(actions.label('/ma "Cure IV" <me>') == 'Cure IV')
assert(actions.kind('//gs c accuracy') == 'command')
local path = 'data/test_storage.lua'
assert(storage.save(path, normalized))
assert(storage.load(path).active_palette == 'default')
assert(storage.save(path, normalized))
assert(io.open(path .. '.bak', 'rb'):read('*a'):match('return'))
assert(m.normalize(storage.load(path)).bars[1].scope == 'global')
os.remove(path)
os.remove(path .. '.bak')
print('MODEL TESTS PASSED: 24 assertions across model, palettes, profiles, storage, action labels')
